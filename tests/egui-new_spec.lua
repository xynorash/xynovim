--- Build a ZIP at `out` with the entries (names are used as given).
local function build_zip(out, entries)
  vim.fn.mkdir(vim.fs.dirname(out), "p")
  local spec = H.tmpdir() .. "/spec.json"
  write(spec, vim.json.encode(entries))
  local r = vim.system({ "python3", "-I", "-c", PY, out, spec }, { text = true }):wait(20000)
  H.eq(0, r.code, r.stderr)
end

--- The fake template as a repo archive: <top>/<files>.
local function fake_zip(out, extra, top)
  top = top or "eframe_template-main"
  local entries = {}
  for _, e in ipairs(template_files(extra)) do
    entries[#entries + 1] = vim.tbl_extend("force", e, { name = top .. "/" .. e.name })
  end
  build_zip(out, entries)
end

--- file:// base_url serving the fake template at <root>/emilk/eframe_template/archive/main.zip
local function file_template(extra, top)
  local root = H.tmpdir()
  fake_zip(root .. "/emilk/eframe_template/archive/main.zip", extra, top)
  vim.g.xynovim_egui_template = { base_url = "file://" .. root }
  return root
end

--- A tiny HTTP server in this nvim: ETag / If-None-Match like GitHub's codeload.
local function serve(body, etag)
  local srv = vim.uv.new_tcp()
  srv:bind("127.0.0.1", 0)
  local state = { requests = {}, body = body, etag = etag, mode = "ok", port = srv:getsockname().port }
  srv:listen(8, function()
    local c = vim.uv.new_tcp()
    srv:accept(c)
    local buf = ""
    c:read_start(function(err, chunk)
      if err or not chunk then
        return c:close()
      end
      buf = buf .. chunk
      if not buf:find("\r\n\r\n", 1, true) then
        return
      end
      c:read_stop()
      local inm = buf:match("[Ii]f%-[Nn]one%-[Mm]atch: ([^\r\n]+)")
      local ua = buf:match("[Uu]ser%-[Aa]gent: ([^\r\n]+)")
      state.requests[#state.requests + 1] = { line = buf:match("^[^\r\n]+"), inm = inm, ua = ua }
      local resp
      if state.mode == "500" then
        resp = "HTTP/1.1 500 Internal Server Error\r\nContent-Length: 0\r\nConnection: close\r\n\r\n"
      elseif inm and inm == state.etag then
        resp = "HTTP/1.1 304 Not Modified\r\nETag: " .. state.etag .. "\r\nConnection: close\r\n\r\n"
      else
        resp = ("HTTP/1.1 200 OK\r\nContent-Type: application/zip\r\nETag: %s\r\nContent-Length: %d\r\nConnection: close\r\n\r\n"):format(
          state.etag, #state.body
        ) .. state.body
      end
      c:write(resp, function()
        c:shutdown(function()
          c:close()
        end)
      end)
    end)
  end)
  state.stop = function()
    if not srv:is_closing() then
      srv:close()
    end
  end
  restores[#restores + 1] = state.stop
  return state
end

--- Answer vim.ui.input from a list (false = cancel); returns the log of the prompts.
local function stub_input(answers)
  local log = {}
  stub(vim.ui, "input", function(opts, cb)
    log[#log + 1] = opts
    local a = table.remove(answers, 1)
    if a == nil then
      error("unexpected prompt: " .. tostring(opts.prompt))
    end
    if a == false then
      return cb(nil)
    end
    cb(a)
  end)
  return log
end

