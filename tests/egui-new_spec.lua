    { name = ".github/workflows/pages.yml", text = PAGES_YML },
    { name = "README.md", text = TEMPLATE_README },
    { name = "fill_template.sh", text = FILL_SH, mode = tonumber("100755", 8) },
    { name = "fill_template.ps1", text = "(Get-Content Cargo.toml)\n" },
    { name = "rust-toolchain", text = TOOLCHAIN },
    { name = "LICENSE-MIT", text = "MIT License\n" },
    { name = "LICENSE-APACHE", text = "Apache License eframe_template\n" },
    { name = "assets/blob.bin", text = "eframe_template\0\1\2" },
  }
  for _, e in ipairs(extra or {}) do
    local replaced
    for i, old in ipairs(f) do
      if old.name == e.name then
        f[i], replaced = e, true
      end
    end
    if not replaced then
      f[#f + 1] = e
    end
  end
  return f
end

