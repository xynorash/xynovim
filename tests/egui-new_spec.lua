local function find_msg(cap, pat, level)
  for _, m in ipairs(cap.list) do
    if tostring(m.msg):find(pat) and (not level or m.level == level) then
      return m
    end
  end
end

--- Run M.create and wait for it; returns err, info.
local function create(p)
  local done
  E.create(p, function(err, info)
    done = { err, info }
  end)
  H.wait_for(function()
    return done ~= nil
  end, 60000, "EguiNew create did not finish")
  return done[1], done[2]
end

