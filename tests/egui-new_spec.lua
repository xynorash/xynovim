local restores = {}
local function stub(t, k, v)
  local orig = t[k]
  t[k] = v
  restores[#restores + 1] = function()
    t[k] = orig
  end
end

local function need_tools()
  for _, t in ipairs({ "curl", "unzip", "python3" }) do
    if vim.fn.executable(t) ~= 1 then
      return skip(t .. " not found")
    end
  end
end

local function cache_dir()
  return vim.fn.stdpath("cache") .. "/xynovim"
end

local saved_g = {}
before_each(function()
  vim.fn.delete(cache_dir(), "rf")
  for _, k in ipairs({
    "xynovim_egui_template",
    "xynovim_egui_keep_toolchain_pin",
    "xynovim_egui_build_after_new",
    "xynovim_projects_dir",
  }) do
    saved_g[k] = vim.g[k]
    vim.g[k] = nil
  end
end)

after_each(function()
  for i = #restores, 1, -1 do
    pcall(restores[i])
  end
  restores = {}
  for k, v in pairs(saved_g) do
    vim.g[k] = v
  end
  vim.fn.delete(cache_dir(), "rf")
  -- opening src/main.rs of a generated project starts the Rust language servers
  pcall(function()
    for _, c in ipairs(vim.lsp.get_clients()) do
      c:stop(true)
    end
  end)
  pcall(vim.cmd, "silent! %bwipeout!")
  pcall(vim.cmd, "cd " .. vim.fn.fnameescape(vim.env.HOME or "/"))
end)

local function read(path)
  local f = io.open(path, "rb")
  if not f then
    return nil
  end
  local s = f:read("*a")
  f:close()
  return s
end

local function write(path, text)
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  local f = assert(io.open(path, "wb"))
  f:write(text)
  f:close()
end

