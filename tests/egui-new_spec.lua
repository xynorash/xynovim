describe("the real template (network)", function()
  it("downloads eframe_template and personalises it as my_gui_app", function()
    need_tools()
    local r = vim.system({ "curl", "-sSIL", "--max-time", "10", "-o", "/dev/null", "https://github.com/emilk/eframe_template/archive/main.zip" }):wait(15000)
    if r.code ~= 0 then
      return skip("no network to github.com")
    end
    local parent = H.tmpdir()
    local err, info = create({ crate = "my_gui_app", author_name = "Jane Doe", author_email = "jane@example.com", parent = parent })
    H.is_nil(err, err)
    local dir = info.dir
    -- no eframe_template token outside the links to the template
    local function scan(d, rel)
      for name, typ in vim.fs.dir(d) do
        local r2 = rel and (rel .. "/" .. name) or name
        if typ == "directory" then
          if name ~= ".git" then
            scan(d .. "/" .. name, r2)
          end
        elseif typ == "file" and not name:match("^LICEN[CS]E") then
          local t = read(d .. "/" .. name)
          if t and #t < 1024 * 1024 and not t:find("\0", 1, true) then
            H.eq(t, E.replace_token(t, "my_gui_app"), "template token left in " .. r2)
            H.no_match(t, "eframe template", true, "template title left in " .. r2)
          end
        end
      end
    end
    scan(dir)
    H.has(read(dir .. "/src/main.rs"), "my_gui_app::TemplateApp")
    H.no_match(read(dir .. "/src/main.rs"), "eframe_template::", true)
    local sw = read(dir .. "/assets/sw.js")
    H.has(sw, "./my_gui_app.js")
    H.has(sw, "./my_gui_app_bg.wasm")
    H.has(read(dir .. "/index.html"), "<title>my gui app</title>")
    H.has(read(dir .. "/Cargo.toml"), 'authors = ["Jane Doe <jane@example.com>"]')
    H.is_nil(vim.uv.fs_stat(dir .. "/fill_template.sh"))
    if vim.fn.executable("cargo") == 1 then
      -- RUSTUP_TOOLCHAIN=stable: the project's rust-toolchain would make rustup download 1.95.0
      local m = vim.system({ "cargo", "read-manifest" }, { cwd = dir, text = true, env = { RUSTUP_TOOLCHAIN = "stable" } }):wait(60000)
      if m.code == 0 then
        local manifest = vim.json.decode(m.stdout)
        H.eq("my_gui_app", manifest.name)
        H.eq({ "Jane Doe <jane@example.com>" }, manifest.authors)
      end
    end
  end)
end)
